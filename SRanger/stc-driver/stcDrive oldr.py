#!/usr/bin/env python3
"""
Replay .rtspec CSP traces (generated by RoboTool's test-gen for SimSMovement)
against the compiled console program (code-gen/C/SRanger/main).

Per the file's own header, each line is "t0, ..., tn, fevent": a valid
prefix <t0,...,tn> followed by a final forbidden event 'fevent' that must
NOT occur immediately after that prefix. This is refusal/negative testing,
so the verdict per trace is:

  INCONCLUSIVE -- the SUT didn't reproduce the prefix as expected, so
                  whether it refuses fevent can't be determined.
  PASS         -- the prefix was reproduced exactly, and fevent did NOT
                  occur next (it was refused).
  FAIL         -- the prefix was reproduced exactly, and fevent DID occur
                  next (the forbidden behaviour happened).

Mapping from CSP trace events to console interaction:
  registerRead.i_obstacle.true   -> type "obstacle" before flushing the cycle
  registerRead.i_obstacle.false  -> don't type "obstacle" for the cycle
  registerWrite.o_move.X.Y       -> a printed "output move(X.000000,Y.000000)" line
  registerWrite.o_stop           -> a printed "output stop" line
  tock                           -> end of one input/output cycle (the "---------------------" divider)
"""
import argparse
import re
import subprocess
import sys
import threading
from pathlib import Path

TRACE_RE = re.compile(r"^t(\d+):\s*(.+)$")
DIVIDER = "---------------------"
MOVE_RE = re.compile(r"output move\(([-\d.]+),\s*([-\d.]+)\)")
STOP_RE = re.compile(r"output stop")
TRACE_TIMEOUT = 5.0


def parse_event(ev):
    ev = ev.strip()
    if ev == "tock":
        return ("tock", None, None)
    parts = ev.split(".")
    action = parts[0].rsplit("::", 1)[-1]
    var = parts[1].rsplit("::", 1)[-1]
    args = parts[2:]
    return (action, var, args)


def load_traces(rtspec_path):
    traces = {}
    for line in Path(rtspec_path).read_text().splitlines():
        m = TRACE_RE.match(line.strip())
        if not m:
            continue
        tid, body = m.groups()
        events = [parse_event(e) for e in body.split(",")]
        traces[int(tid)] = events
    return traces


def event_token(action, var, args):
    """Render a registerWrite/tock event as the string it would appear as on stdout."""
    if action == "tock":
        return "tock"
    if var == "o_move":
        v1, v2 = float(args[0]), float(args[1])
        return f"output move({v1:.6f},{v2:.6f})"
    if var == "o_stop":
        return "output stop"
    raise ValueError(f"event has no observable token: {action}.{var}")


def split_trace(events):
    """Split a trace into (closed_cycles, open_cycle, fevent_token).

    closed_cycles: list of (obstacle, expected_tokens) for each cycle in the
    prefix that is terminated by a 'tock' -- must match exactly.
    open_cycle: (obstacle, expected_tokens) for the trailing, not-yet-closed
    cycle that fevent applies to.
    """
    fevent = event_token(*events[-1])
    prefix = events[:-1]
    closed_cycles = []
    obstacle = False
    expected = []
    for action, var, args in prefix:
        if action == "tock":
            closed_cycles.append((obstacle, expected))
            obstacle, expected = False, []
            continue
        if action == "registerRead" and var == "i_obstacle":
            obstacle = args[0] == "true"
        elif action == "registerWrite":
            expected.append(event_token(action, var, args))
    return closed_cycles, (obstacle, expected), fevent


def next_token(proc):
    """Read stdout until the next output line or the cycle divider, and
    return it as a token ('output move(...)' / 'output stop' / 'tock')."""
    while True:
        line = proc.stdout.readline()
        if line == "":
            raise RuntimeError("program exited unexpectedly")
        m = MOVE_RE.search(line)
        if m:
            return f"output move({float(m.group(1)):.6f},{float(m.group(2)):.6f})"
        if STOP_RE.search(line):
            return "output stop"
        if DIVIDER in line:
            return "tock"


def send_cycle_input(proc, obstacle):
    if obstacle:
        proc.stdin.write("obstacle\n")
    proc.stdin.write("\n")
    proc.stdin.flush()


def terminate(proc):
    try:
        proc.stdin.write("$end\n")
        proc.stdin.flush()
        proc.stdout.readline()
    except Exception:
        pass


def run_trace(binary, closed_cycles, open_cycle, fevent):
    # the program fully-buffers stdout when it isn't a tty, so force
    # line-buffering via stdbuf or the prompt/output text never gets flushed
    # until the process exits, deadlocking the read loop below.
    proc = subprocess.Popen(
        ["stdbuf", "-oL", binary],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
        bufsize=1,
    )
    timer = threading.Timer(TRACE_TIMEOUT, proc.kill)
    timer.start()
    detail = []
    verdict = "INCONCLUSIVE"
    try:
        for obstacle, expected in closed_cycles:
            send_cycle_input(proc, obstacle)
            actual = [next_token(proc)]
            while actual[-1] != "tock":
                actual.append(next_token(proc))
            actual = actual[:-1]  # drop the trailing 'tock' sentinel
            detail.append(("closed cycle", obstacle, expected, actual))
            if actual != expected:
                terminate(proc)
                timer.cancel()
                return verdict, detail

        obstacle, expected = open_cycle
        send_cycle_input(proc, obstacle)
        actual = []
        mismatch = False
        for exp_tok in expected:
            tok = next_token(proc)
            actual.append(tok)
            if tok != exp_tok:
                mismatch = True
                break
        detail.append(("prefix", obstacle, expected, actual))
        if mismatch:
            terminate(proc)
            timer.cancel()
            return verdict, detail

        observed = next_token(proc)
        detail.append(("forbidden event check", None, [fevent], [observed]))
        verdict = "FAIL" if observed == fevent else "PASS"

        terminate(proc)
    finally:
        timer.cancel()
        try:
            proc.stdin.close()
        except Exception:
            pass
        try:
            proc.wait(timeout=TRACE_TIMEOUT)
        except subprocess.TimeoutExpired:
            proc.kill()
    return verdict, detail


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("rtspec", help="path to the .rtspec trace file")
    ap.add_argument("system_under_test", help="path to the compiled program to drive (e.g. .../SRanger/main)")
    ap.add_argument("--verbose", action="store_true", help="show per-cycle detail for PASS too")
    ap.add_argument(
        "--results-file",
        default="results.txt",
        help="write a counts + trace-id-per-verdict summary to this file (default: results.txt)",
    )
    ap.add_argument("--traces", nargs="*", type=int, help="trace ids to run, e.g. --traces 0 1 79 (default: all)")
    args = ap.parse_args()

    traces = load_traces(args.rtspec)
    ids = args.traces if args.traces else sorted(traces)

    counts = {"PASS": 0, "FAIL": 0, "INCONCLUSIVE": 0, "ERROR": 0}
    verdicts = {}
    for tid in ids:
        if tid not in traces:
            print(f"t{tid}: not found in {args.rtspec}")
            continue
        closed_cycles, open_cycle, fevent = split_trace(traces[tid])
        try:
            verdict, detail = run_trace(args.system_under_test, closed_cycles, open_cycle, fevent)
        except RuntimeError as e:
            print(f"t{tid}: ERROR ({e})")
            counts["ERROR"] += 1
            verdicts[tid] = "ERROR"
            continue
        counts[verdict] += 1
        verdicts[tid] = verdict
        print(f"t{tid}: {verdict}")
        if verdict != "PASS" or args.verbose:
            for label, obstacle, expected, actual in detail:
                tag = "ok" if expected == actual else "MISMATCH"
                ob = f" obstacle={obstacle}" if obstacle is not None else ""
                print(f"    {label}{ob} [{tag}]")
                print(f"        expected: {expected}")
                print(f"        actual:   {actual}")

    total = len(ids)
    print(
        f"\n{counts['PASS']} pass, {counts['FAIL']} fail, "
        f"{counts['INCONCLUSIVE']} inconclusive, {counts['ERROR']} error, {total} total"
    )

    lines = [
        f"{counts['PASS']} pass, {counts['FAIL']} fail, "
        f"{counts['INCONCLUSIVE']} inconclusive, {counts['ERROR']} error, {total} total",
        "",
    ]
    for label in ("PASS", "FAIL", "INCONCLUSIVE", "ERROR"):
        tids = sorted(tid for tid, v in verdicts.items() if v == label)
        lines.append(f"{label} ({len(tids)}): {', '.join(f't{t}' for t in tids)}")
    Path(args.results_file).write_text("\n".join(lines) + "\n")
    print(f"\nwrote summary to {args.results_file}")

    sys.exit(1 if counts["FAIL"] or counts["ERROR"] else 0)


if __name__ == "__main__":
    main()
